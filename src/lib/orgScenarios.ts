const ru = (iso: string) => { const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso); return m ? `${m[3]}.${m[2]}.${m[1]}` : ''; };
export function periodText(from: string, to: string): string {
  const a = ru(from), b = ru(to);
  return a && b ? `период с ${a} по ${b}` : a ? `период с ${a}` : b ? `период по ${b}` : 'весь период';
}
export function filesText(names: string[]): string {
  const n = names.map((x) => x.split('/').pop() || x).filter(Boolean);
  if (!n.length) return 'документы этого чата';
  const head = n.slice(0, 10).map((x) => `«${x}»`).join(', ');
  return n.length > 10 ? `${head} и ещё ${n.length - 10}` : head;
}

export function scenarioText(id: ScenarioId, p: { org: string; inn?: string | null; from: string; to: string; files: string[] }): string {
  const org = `«${p.org}»${p.inn ? ` (ИНН ${p.inn})` : ''}`;
  return TPL[id].replaceAll('{организация}', org).replaceAll('{период}', periodText(p.from, p.to)).replaceAll('{файлы}', filesText(p.files));
}
