import { describe, expect, it } from 'vitest';
import { introVoice } from '@/lib/introMarks';
import { sameManner } from '@/lib/memory';

describe('голос знакомства', () => {
  it('«Отлично, понял: …» -> «Поняла: …»; «Понял», «записал», «учёл», «рад» — в женском роде', () => {
    expect(introVoice('Отлично, понял: Python, бэкенд.\n\nОсталось два вопроса.')).toBe('Поняла: Python, бэкенд.\n\nОсталось два вопроса.');
    expect(introVoice('Понял, записал и учёл. Рад помочь.')).toBe('Поняла, записала и учла. Рада помочь.');
    expect(introVoice('Отлично!')).toBe('Отлично!');
  });
  it('оценка его ответа отдельным предложением — убрана, если есть что-то ещё', () => {
    expect(introVoice('Python и LaTeX — классика, всё сходится. Как вам удобнее получать ответы?')).toBe('Как вам удобнее получать ответы?');
    expect(introVoice('Это к нам прямое попадание.')).toBe('Это к нам прямое попадание.');
  });
  it('цитата человека — как есть: «Вы сказали: «понял, сделаю»» не правим', () => {
    expect(introVoice('Поняла. Вы сказали: «понял, сделаю» — это про сроки? Понял.')).toBe('Поняла. Вы сказали: «понял, сделаю» — это про сроки? Поняла.');
    expect(introVoice('Вы написали "записал в 1С" — верно?')).toBe('Вы написали "записал в 1С" — верно?');
  });
  it('не трогает чужие слова: «понятно», «записать», «запись», «рада» — как есть', () => {
    expect(introVoice('Понятно. Можно записать в 1С; рада, что так.')).toBe('Понятно. Можно записать в 1С; рада, что так.');
  });
});

describe('одна манера разными словами', () => {
  it('«Хочет короткие ответы в формате списка» = «Отвечать короче и списком»; «без эмодзи» ≠ «с эмодзи»; разное — разное', () => {
    expect(sameManner('Хочет короткие ответы в формате списка', 'Отвечать короче и списком')).toBe(true);
    expect(sameManner('Пишет без эмодзи и коротко', 'Пишет с эмодзи и коротко')).toBe(false);
    expect(sameManner('Хочет итог в первой строке', 'Просит таблицы вместо списков')).toBe(false);
  });
});
